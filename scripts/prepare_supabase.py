"""Generate a transactional Supabase setup script from the existing SQLite records."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sqlite3

ROOT = Path(__file__).resolve().parents[1]


def sql_literal(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def build_setup(database: Path) -> tuple[str, int]:
    with sqlite3.connect(database.resolve().as_uri() + "?mode=ro", uri=True) as connection:
        records = connection.execute(
            "SELECT material_id, role, name, record_json FROM material_candidates ORDER BY material_id"
        ).fetchall()
    statements = [
        "-- Generated by scripts/prepare_supabase.py. Run once in the Supabase SQL Editor.",
        "-- Preserves existing matching records; conflicting records abort the transaction.",
        "begin;",
        "set local standard_conforming_strings = on;",
        (ROOT / "supabase/schema.sql").read_text(),
        "create temporary table sensora_import (like public.material_candidates including all) on commit drop;",
    ]
    for material_id, role, name, payload in records:
        record = json.loads(payload)
        if (record.get("material_id"), record.get("role"), record.get("name")) != (material_id, role, name):
            raise ValueError(f"SQLite record identity does not match its columns: {material_id}")
        values = ", ".join(sql_literal(v) for v in (material_id, role, name))
        record_sql = sql_literal(json.dumps(record, ensure_ascii=False, sort_keys=True)) + "::jsonb"
        statements.append(
            "insert into sensora_import (material_id, role, name, record_json)\n"
            f"values ({values}, {record_sql});"
        )
    statements += [
        "insert into public.material_candidates (material_id, role, name, record_json)\n"
        "select material_id, role, name, record_json from sensora_import\n"
        "on conflict (material_id) do nothing;",
        """do $$ begin
    if exists (
        select 1 from sensora_import src
        left join public.material_candidates dst using (material_id)
        where dst.material_id is null or src.role <> dst.role or src.name <> dst.name
            or src.record_json <> dst.record_json
    ) then
        raise exception 'Existing Supabase record differs from SQLite; import cancelled.';
    end if;
end; $$;""",
        "notify pgrst, 'reload schema';", "commit;", "",
    ]
    return "\n\n".join(statements), len(records)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--database", type=Path, default=ROOT / "data/materials.sqlite3")
    parser.add_argument("--output", type=Path, default=ROOT / "supabase/setup.sql")
    args = parser.parse_args()
    sql, count = build_setup(args.database)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(sql)
    print(f"Prepared {args.output} with {count} materials. No remote data was changed.")


if __name__ == "__main__":
    main()
